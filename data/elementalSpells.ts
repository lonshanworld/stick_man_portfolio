export type SpellTarget = 'self' | 'ahead' | 'nearest' | 'allies' | 'area';
export type SpellAction =
  | 'damageReaction'
  | 'shield'
  | 'restore'
  | 'cleanse'
  | 'stun'
  | 'freeze'
  | 'root'
  | 'slow'
  | 'pull'
  | 'push'
  | 'teleport'
  | 'levitate'
  | 'cloak'
  | 'rewind'
  | 'stasis'
  | 'silence'
  | 'summon';

